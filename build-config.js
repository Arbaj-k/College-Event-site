/*
 * Creates the browser-safe Supabase config at build time.
 * Reads local .env (if present) and process environment variables.
 * Only the public anon/publishable key belongs in this generated browser config.
 */
const fs = require('fs');
const path = require('path');

const root = __dirname;
const target = path.join(root, 'js', 'config.js');

function readDotEnv() {
  const file = path.join(root, '.env');
  if (!fs.existsSync(file)) return {};
  const values = {};
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^\s*(?:export\s+)?([A-Z][A-Z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (!match || match[1].startsWith('#')) continue;
    let value = match[2];
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) value = value.slice(1, -1);
    values[match[1]] = value.replace(/\\n/g, '\n');
  }
  return values;
}
const local = readDotEnv();
const url = String(process.env.SUPABASE_URL || local.SUPABASE_URL || '').trim().replace(/\/$/, '');
const key = String(process.env.SUPABASE_ANON_KEY || local.SUPABASE_ANON_KEY || '').trim();

function fail(message) {
  console.error('[build-config] ' + message);
  process.exit(1);
}
if (!url || !key || /YOUR-|PLACEHOLDER|CHANGE_ME/i.test(url + key)) {
  fail('Missing SUPABASE_URL or SUPABASE_ANON_KEY. Set GitHub Actions repository variables or create a local .env from .env.example.');
}
if (!/^https:\/\/[a-z0-9-]+\.supabase\.(co|in)$/i.test(url)) {
  fail('SUPABASE_URL must be a valid Supabase project URL.');
}
if (/^sb_secret_/i.test(key)) fail('A Supabase secret key was supplied. Only the anon/publishable key may be exposed to the browser.');
if (key.split('.').length === 3) {
  try {
    const payload = JSON.parse(Buffer.from(key.split('.')[1], 'base64url').toString('utf8'));
    if (payload.role !== 'anon') fail('The supplied JWT is not an anon key. Service-role keys are forbidden in browser builds.');
  } catch (error) {
    if (String(error.message).includes('forbidden') || String(error.message).includes('not an anon')) throw error;
    fail('SUPABASE_ANON_KEY is not a valid public anon/publishable key.');
  }
}
const output = '/* Generated by build-config.js. Do not edit or commit real values. */\n' +
  'window.CE_CONFIG = ' + JSON.stringify({ SUPABASE_URL: url, SUPABASE_ANON_KEY: key }, null, 2) + ';\n';
fs.writeFileSync(target, output, { mode: 0o600 });
console.log('[build-config] Browser config generated from environment variables.');
